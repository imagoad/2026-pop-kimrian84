# ============================================================
# 📊 우리 동네 인구, 얼마나 "퍼져" 있을까?
# ------------------------------------------------------------
# 이 앱은 전국 읍·면·동의 "총인구"가 얼마나 퍼져있는지를
# 아주 간단하게 눈으로 확인해보는 앱이에요.
# describe() 표 → 히스토그램 → 상자그림, 이렇게 3단계로 보여줄게요.
# ============================================================

import streamlit as st
import pandas as pd
import plotly.express as px
import plotly.graph_objects as go

# 페이지 기본 설정 (제목, 넓은 화면)
st.set_page_config(page_title="우리 동네 인구 퍼짐 보기", layout="wide")

st.title("🏘️ 우리 동네 인구, 얼마나 퍼져 있을까?")
st.write(
    "전국 읍·면·동(가장 작은 행정 단위)의 **총인구**가 "
    "동네마다 얼마나 다르게 퍼져 있는지 살펴보는 앱이에요. "
    "복잡한 설정 없이 아래로 스크롤만 하면 돼요 😊"
)

# ------------------------------------------------------------
# 1단계. 데이터 불러오기
# ------------------------------------------------------------
# @st.cache_data 를 붙이면, 한 번 불러온 데이터를 저장해두고
# 다음에는 다시 인터넷에서 안 받아와서 앱이 훨씬 빨라져요.
DATA_URL = "https://raw.githubusercontent.com/greatsong/modudata/main/data/population_yearly.csv.gz"


@st.cache_data
def load_data(url):
    # 파일 확장자가 .gz 라서, pandas가 알아서 압축을 풀며 읽어줘요.
    df = pd.read_csv(url, compression="gzip", low_memory=False)
    return df


with st.spinner("데이터를 불러오는 중이에요... 잠시만 기다려주세요 ⏳"):
    df = load_data(DATA_URL)

st.success(f"데이터를 잘 불러왔어요! (전체 {len(df):,}행)")

# ------------------------------------------------------------
# 2단계. 가장 최신 연도만 남기기
# ------------------------------------------------------------
# '연도' 열에서 제일 큰 값(가장 최근 연도)만 골라서 사용할게요.
최신연도 = df["연도"].max()
df_최신 = df[df["연도"] == 최신연도].copy()

st.info(f"가장 최신 연도인 **{최신연도}년** 데이터만 사용할게요. "
        f"(읍·면·동 개수: {len(df_최신):,}개)")

# ------------------------------------------------------------
# 3단계. '총인구' 열 만들기
# ------------------------------------------------------------
# 열 이름이 '남_0세', '남_1세', ... , '여_0세', '여_1세', ... 처럼
# 나이 하나마다 남/여 인구 열이 따로 있어요.
# 이 열들을 동네(행)마다 전부 더해서 '총인구' 열 하나로 만들게요.
남열_목록 = [col for col in df_최신.columns if col.startswith("남_")]
여열_목록 = [col for col in df_최신.columns if col.startswith("여_")]

df_최신["총인구"] = df_최신[남열_목록 + 여열_목록].sum(axis=1)

st.write(
    f"남자 나이별 열 {len(남열_목록)}개 + 여자 나이별 열 {len(여열_목록)}개를 "
    f"모두 더해서 **'총인구'** 열을 새로 만들었어요."
)

st.divider()

# ------------------------------------------------------------
# 4단계-1. describe() 결과 표 보여주기
# ------------------------------------------------------------
# describe()는 평균, 최소값, 최대값처럼 데이터가 대략 어떻게
# 생겼는지 한눈에 알려주는 요약 통계 표예요.
st.header("1️⃣ 총인구 요약 통계 (describe)")
st.write("동네별 총인구가 대략 어떤 범위에, 어떻게 퍼져 있는지 숫자로 먼저 확인해볼게요.")

describe_표 = df_최신["총인구"].describe().to_frame(name="총인구")
st.dataframe(describe_표, use_container_width=True)

st.caption(
    "💡 **count**는 동네 개수, **mean**은 평균, **std**는 흩어진 정도(표준편차), "
    "**min/max**는 가장 작은/큰 값, **25%·50%·75%**는 데이터를 4등분했을 때의 위치예요."
)

st.divider()

# ------------------------------------------------------------
# 4단계-2. 히스토그램 (막대로 분포 보기)
# ------------------------------------------------------------
st.header("2️⃣ 총인구 히스토그램")
st.write(
    "동네들을 인구 구간별로 나눠서, 각 구간에 몇 개 동네가 있는지 막대로 보여줘요. "
    "막대가 높을수록 그 인구 규모의 동네가 많다는 뜻이에요. "
    "그래프 위에서 **마우스로 드래그하면 확대**, 더블클릭하면 원래대로 돌아와요."
)

fig_히스토그램 = px.histogram(
    df_최신,
    x="총인구",
    nbins=50,
    labels={"총인구": "총인구 (명)", "count": "동네 개수"},
    title=f"{최신연도}년 읍·면·동 총인구 분포",
)
fig_히스토그램.update_layout(
    yaxis_title="동네 개수",
    bargap=0.05,
)
st.plotly_chart(fig_히스토그램, use_container_width=True)

st.divider()

# ------------------------------------------------------------
# 4단계-3. 상자그림 (박스플롯으로 분포 보기)
# ------------------------------------------------------------
st.header("3️⃣ 총인구 상자그림 (박스플롯)")
st.write(
    "상자그림은 데이터가 어디에 몰려있고, 어디까지 퍼져있는지, "
    "그리고 유난히 튀는 동네(이상치)는 없는지를 한 번에 보여줘요. "
    "**점 위에 마우스를 올리면** 어떤 동네인지, 인구가 몇 명인지 바로 확인할 수 있어요."
)

fig_박스플롯 = px.box(
    df_최신,
    y="총인구",
    points="outliers",  # 튀는 값(이상치)만 점으로 표시
    labels={"총인구": "총인구 (명)"},
    title=f"{최신연도}년 읍·면·동 총인구 상자그림",
    hover_data=["시도", "시군구", "동"],
)
st.plotly_chart(fig_박스플롯, use_container_width=True)

st.caption(
    "💡 상자의 가운데 선은 중앙값, 상자의 위아래 끝은 25%·75% 지점이에요. "
    "상자 밖 점들은 다른 동네보다 인구가 유난히 많거나 적은 '튀는' 동네랍니다."
)

# ============================================================
# 5단계. 인구구조가 가장 비슷한 지역 Top 5 찾기
# ------------------------------------------------------------
# '인구구조'란 나이별 인구 비율(모양)을 말해요.
# 총인구 크기가 달라도, 나이별 비율(그래프 모양)이 비슷하면
# "인구구조가 비슷하다"고 볼 수 있어요.
# ============================================================
st.divider()
st.header("4️⃣ 나와 인구구조가 가장 비슷한 지역 Top 5")
st.write(
    "동네 하나를 고르면, 전국에서 **나이별 인구 비율(모양)**이 "
    "가장 비슷한 지역 5곳을 찾아드려요. "
    "(단순히 인구 '규모'가 비슷한 게 아니라, 나이대별 비중이 비슷한 지역이에요!)"
)

# ------------------------------------------------------------
# 5-1. 지역 선택 (검색 입력 + 드롭다운 선택 동시 지원)
# ------------------------------------------------------------
# 시도 + 시군구 + 동 + 코드를 합쳐서 지역마다 겹치지 않는 이름표를 만들어요.
df_최신["지역명"] = (
    df_최신["시도"].fillna("")
    + " "
    + df_최신["시군구"].fillna("")
    + " "
    + df_최신["동"].fillna("")
).str.strip()
df_최신["지역표시명"] = df_최신["지역명"] + " (" + df_최신["코드"].astype(str) + ")"

지역_검색어 = st.text_input("🔍 비교 기준이 될 지역을 검색해보세요 (예: 강남, 해운대, 종로)", "")

if 지역_검색어.strip():
    후보_목록 = df_최신[df_최신["지역명"].str.contains(지역_검색어.strip(), na=False)]
else:
    후보_목록 = df_최신

if len(후보_목록) == 0:
    st.warning("검색 결과가 없어요. 다른 키워드로 검색해보세요.")
    st.stop()

기준_지역_표시명 = st.selectbox(
    "위 검색 결과 중, 기준이 될 동네를 하나 선택하세요",
    options=후보_목록["지역표시명"].tolist(),
)

# ------------------------------------------------------------
# 5-2. 나이별 인구 '비율' 계산하기 (인구구조 비교의 핵심!)
# ------------------------------------------------------------
# '계_0세', '계_1세', ... '계_100세 이상' 열을 모아서
# 각 지역의 나이별 인구 벡터를 만들고,
# 그 지역 총인구로 나눠서 '비율(구조)'로 바꿔줘요.
계열_목록 = [col for col in df_최신.columns if col.startswith("계_")]

나이별_인구 = df_최신[계열_목록].to_numpy(dtype=float)
지역별_총합 = 나이별_인구.sum(axis=1, keepdims=True)
지역별_총합[지역별_총합 == 0] = 1  # 인구 0인 동네가 있으면 0으로 나누기 방지

나이별_비율 = 나이별_인구 / 지역별_총합  # 지역마다 합이 1이 되는 '인구구조' 벡터

# ------------------------------------------------------------
# 5-3. 기준 지역과 다른 모든 지역 사이의 '거리' 계산하기
# ------------------------------------------------------------
# 유클리드 거리가 가까울수록(작을수록) 인구구조 모양이 비슷하다는 뜻이에요.
기준_행_번호 = df_최신.index[df_최신["지역표시명"] == 기준_지역_표시명][0]
기준_위치 = df_최신.index.get_loc(기준_행_번호)
기준_비율벡터 = 나이별_비율[기준_위치]

거리_배열 = ((나이별_비율 - 기준_비율벡터) ** 2).sum(axis=1) ** 0.5

df_최신["구조거리"] = 거리_배열

# 기준 지역 자기 자신은 제외하고, 거리가 가까운(비슷한) 순서로 5개 뽑기
top5 = (
    df_최신[df_최신["지역표시명"] != 기준_지역_표시명]
    .sort_values("구조거리")
    .head(5)
)

st.subheader(f"'{기준_지역_표시명}'과(와) 인구구조가 가장 비슷한 지역 Top 5")
st.dataframe(
    top5[["지역명", "총인구", "구조거리"]]
    .rename(columns={"구조거리": "구조 차이(작을수록 비슷)"})
    .reset_index(drop=True),
    use_container_width=True,
)

# ------------------------------------------------------------
# 5-4. 나이별 인구구조 비교 그래프 (Plotly 꺾은선)
# ------------------------------------------------------------
연령_라벨_목록 = [col.replace("계_", "") for col in 계열_목록]

fig_구조비교 = go.Figure()

# 기준 지역: 굵고 진한 선으로 강조
fig_구조비교.add_trace(
    go.Scatter(
        x=연령_라벨_목록,
        y=기준_비율벡터,
        mode="lines",
        name=f"⭐ {기준_지역_표시명} (기준)",
        line=dict(width=4, color="#E45756"),
    )
)

# Top 5 비슷한 지역들: 얇은 선으로 겹쳐 그리기
for _, row in top5.iterrows():
    행_위치 = df_최신.index.get_loc(row.name)
    fig_구조비교.add_trace(
        go.Scatter(
            x=연령_라벨_목록,
            y=나이별_비율[행_위치],
            mode="lines",
            name=row["지역표시명"],
            line=dict(width=1.8, dash="dot"),
            opacity=0.85,
        )
    )

fig_구조비교.update_layout(
    height=550,
    hovermode="x unified",
    xaxis_title="나이",
    yaxis_title="비율 (해당 나이 인구 ÷ 총인구)",
    yaxis_tickformat=".1%",
    legend_title="지역",
    title="기준 지역 vs 인구구조가 비슷한 Top 5 지역",
)
fig_구조비교.update_xaxes(tickangle=-45)

st.plotly_chart(fig_구조비교, use_container_width=True)

st.caption(
    "💡 선 모양이 비슷할수록 나이대별 인구 비중이 비슷한 지역이에요. "
    "예를 들어 20~30대가 많은 '젊은 동네'는 서로 비슷한 모양으로 나타나고, "
    "고령 인구가 많은 지역끼리도 비슷한 모양을 보여요."
)

st.divider()
st.caption("데이터 출처: greatsong/modudata (population_yearly.csv.gz)")
