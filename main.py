# ============================================================
# 📊 우리 동네 인구, 얼마나 "퍼져" 있을까?
# ------------------------------------------------------------
# 이 앱은 전국 읍·면·동의 "총인구"가 얼마나 퍼져있는지를
# 아주 간단하게 눈으로 확인해보는 앱이에요.
# describe() 표 → 히스토그램 → 상자그림, 이렇게 3단계로 보여줄게요.
# ============================================================

import streamlit as st
import pandas as pd
import plotly.express as px

# 페이지 기본 설정 (제목, 넓은 화면)
st.set_page_config(page_title="우리 동네 인구 퍼짐 보기", layout="wide")

st.title("🏘️ 우리 동네 인구, 얼마나 퍼져 있을까?")
st.write(
    "전국 읍·면·동(가장 작은 행정 단위)의 **총인구**가 "
    "동네마다 얼마나 다르게 퍼져 있는지 살펴보는 앱이에요. "
    "복잡한 설정 없이 아래로 스크롤만 하면 돼요 😊"
)

# ------------------------------------------------------------
# 1단계. 데이터 불러오기
# ------------------------------------------------------------
# @st.cache_data 를 붙이면, 한 번 불러온 데이터를 저장해두고
# 다음에는 다시 인터넷에서 안 받아와서 앱이 훨씬 빨라져요.
DATA_URL = "https://raw.githubusercontent.com/greatsong/modudata/main/data/population_yearly.csv.gz"


@st.cache_data
def load_data(url):
    # 파일 확장자가 .gz 라서, pandas가 알아서 압축을 풀며 읽어줘요.
    df = pd.read_csv(url, compression="gzip", low_memory=False)
    return df


with st.spinner("데이터를 불러오는 중이에요... 잠시만 기다려주세요 ⏳"):
    df = load_data(DATA_URL)

st.success(f"데이터를 잘 불러왔어요! (전체 {len(df):,}행)")

# ------------------------------------------------------------
# 2단계. 가장 최신 연도만 남기기
# ------------------------------------------------------------
# '연도' 열에서 제일 큰 값(가장 최근 연도)만 골라서 사용할게요.
최신연도 = df["연도"].max()
df_최신 = df[df["연도"] == 최신연도].copy()

st.info(f"가장 최신 연도인 **{최신연도}년** 데이터만 사용할게요. "
        f"(읍·면·동 개수: {len(df_최신):,}개)")

# ------------------------------------------------------------
# 3단계. '총인구' 열 만들기
# ------------------------------------------------------------
# 열 이름이 '남_0세', '남_1세', ... , '여_0세', '여_1세', ... 처럼
# 나이 하나마다 남/여 인구 열이 따로 있어요.
# 이 열들을 동네(행)마다 전부 더해서 '총인구' 열 하나로 만들게요.
남열_목록 = [col for col in df_최신.columns if col.startswith("남_")]
여열_목록 = [col for col in df_최신.columns if col.startswith("여_")]

df_최신["총인구"] = df_최신[남열_목록 + 여열_목록].sum(axis=1)

st.write(
    f"남자 나이별 열 {len(남열_목록)}개 + 여자 나이별 열 {len(여열_목록)}개를 "
    f"모두 더해서 **'총인구'** 열을 새로 만들었어요."
)

st.divider()

# ------------------------------------------------------------
# 4단계-1. describe() 결과 표 보여주기
# ------------------------------------------------------------
st.header("1️⃣ 총인구 요약 통계 (describe)")
st.write("동네별 총인구가 대략 어떤 범위에, 어떻게 퍼져 있는지 숫자로 먼저 확인해볼게요.")

describe_표 = df_최신["총인구"].describe().to_frame(name="총인구")
st.dataframe(describe_표, use_container_width=True)

st.caption(
    "💡 **count**는 동네 개수, **mean**은 평균, **std**는 흩어진 정도(표준편차), "
    "**min/max**는 가장 작은/큰 값, **25%·50%·75%**는 데이터를 4등분했을 때의 위치예요."
)

st.divider()

# ------------------------------------------------------------
# 4단계-2. 히스토그램 (막대로 분포 보기)
# ------------------------------------------------------------
st.header("2️⃣ 총인구 히스토그램")
st.write(
    "동네들을 인구 구간별로 나눠서, 각 구간에 몇 개 동네가 있는지 막대로 보여줘요. "
    "막대가 높을수록 그 인구 규모의 동네가 많다는 뜻이에요. "
    "그래프 위에서 **마우스로 드래그하면 확대**, 더블클릭하면 원래대로 돌아와요."
)

fig_히스토그램 = px.histogram(
    df_최신,
    x="총인구",
    nbins=50,
    labels={"총인구": "총인구 (명)", "count": "동네 개수"},
    title=f"{최신연도}년 읍·면·동 총인구 분포",
)
fig_히스토그램.update_layout(
    yaxis_title="동네 개수",
    bargap=0.05,
)
st.plotly_chart(fig_히스토그램, use_container_width=True)

st.divider()

# ------------------------------------------------------------
# 4단계-3. 상자그림 (박스플롯으로 분포 보기)
# ------------------------------------------------------------
st.header("3️⃣ 총인구 상자그림 (박스플롯)")
st.write(
    "상자그림은 데이터가 어디에 몰려있고, 어디까지 퍼져있는지, "
    "그리고 유난히 튀는 동네(이상치)는 없는지를 한 번에 보여줘요. "
    "**점 위에 마우스를 올리면** 어떤 동네인지, 인구가 몇 명인지 바로 확인할 수 있어요."
)

fig_박스플롯 = px.box(
    df_최신,
    y="총인구",
    points="outliers",  # 튀는 값(이상치)만 점으로 표시
    labels={"총인구": "총인구 (명)"},
    title=f"{최신연도}년 읍·면·동 총인구 상자그림",
    hover_data=["시도", "시군구", "동"],
)
st.plotly_chart(fig_박스플롯, use_container_width=True)

st.caption(
    "💡 상자의 가운데 선은 중앙값, 상자의 위아래 끝은 25%·75% 지점이에요. "
    "상자 밖 점들은 다른 동네보다 인구가 유난히 많거나 적은 '튀는' 동네랍니다."
)

st.divider()
st.caption("데이터 출처: greatsong/modudata (population_yearly.csv.gz)")
